#!/bin/bash
# Install BackAtIt.
#
#   ./install.sh                 install for you only  (~/.local)
#   sudo ./install.sh --system   install for everyone  (/usr/local)
#   ./install.sh --uninstall     remove it again
#
# Your settings and statistics live in your home directory and are never
# touched by installing or removing the program.
set -eu

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_FILES="alarm.sh alarmd.sh alertctl.sh lib.sh deps.sh alert.py idle.py settings.py demo-stats.sh instruction.txt about.conf"

MODE=user
ACTION=install
for arg in "$@"; do
    case "$arg" in
        --system)    MODE=system ;;
        --user)      MODE=user ;;
        --uninstall) ACTION=uninstall ;;
        -h|--help)   sed -n '2,9p' "$0" | sed 's/^# \?//'; exit 0 ;;
        *) echo "unknown option: $arg" >&2; exit 64 ;;
    esac
done

if [ "$MODE" = system ]; then
    PREFIX=${PREFIX:-/usr/local}
    [ "$(id -u)" = 0 ] || { echo "--system needs root; try: sudo $0 --system" >&2; exit 1; }
else
    PREFIX=${PREFIX:-$HOME/.local}
fi
LIBDIR="$PREFIX/lib/backatit"
BINDIR="$PREFIX/bin"
APPDIR="$PREFIX/share/applications"
ICONROOT="$PREFIX/share/icons/hicolor"
METADIR="$PREFIX/share/metainfo"

DESKTOP="$APPDIR/backatit.desktop"
LAUNCHER="$BINDIR/backatit"
ICON_SIZES="16 24 32 48 64 128 256"
META="$METADIR/backatit.metainfo.xml"

# ---------------- uninstall ----------------
if [ "$ACTION" = uninstall ]; then
    echo "Removing BackAtIt..."
    [ -r "$LIBDIR/lib.sh" ] && bash -c ". '$LIBDIR/lib.sh'; stop_daemon" 2>/dev/null || true
    rm -rf "$LIBDIR"
    rm -f "$LAUNCHER" "$DESKTOP" "$META"
    for s in $ICON_SIZES; do
        rm -f "$ICONROOT/${s}x${s}/apps/backatit.png"
    done
    rm -f "$ICONROOT/scalable/apps/backatit.svg"
    # Install refreshed the icon cache; refresh it again now the icons are
    # gone, or GTK keeps finding them in the cache and warns ("Could not load
    # a pixbuf from icon theme") in every GTK app that asks for the icon.
    if [ -f "$ICONROOT/icon-theme.cache" ] && command -v gtk-update-icon-cache >/dev/null 2>&1; then
        gtk-update-icon-cache -qtf "$ICONROOT" 2>/dev/null || true
    fi
    # Only drop the login entry if it belongs to the copy being removed.
    # Blindly deleting it would kill the autostart of a second copy — say a
    # working tree in your home directory — that has nothing to do with this.
    AUTO="$HOME/.config/autostart/backatit.desktop"
    if [ -f "$AUTO" ] && grep -qF "Exec=$LIBDIR/" "$AUTO" 2>/dev/null; then
        rm -f "$AUTO"
        echo "  removed the start-at-login entry"
    elif [ -f "$AUTO" ]; then
        echo "  left the start-at-login entry alone (it points somewhere else)"
    fi
    command -v update-desktop-database >/dev/null 2>&1 &&
        update-desktop-database "$APPDIR" 2>/dev/null || true
    echo "Done. Your settings are still in ~/.config/backatit"
    echo "and your statistics in ~/.local/state/backatit."
    exit 0
fi

# ---------------- check what it needs ----------------
# shellcheck source=deps.sh
. "$SRC/deps.sh"
missing=""
command -v bash    >/dev/null 2>&1 || missing="$missing bash"
command -v python3 >/dev/null 2>&1 || missing="$missing python3"
python3 -c 'import gi; gi.require_version("Gtk","3.0")' 2>/dev/null ||
    missing="$missing python3-gi(+gir1.2-gtk-3.0)"
command -v pw-play >/dev/null 2>&1 || command -v paplay >/dev/null 2>&1 ||
    command -v aplay >/dev/null 2>&1 || missing="$missing a-sound-player(pipewire/pulseaudio/alsa)"

if [ -n "$missing" ]; then
    echo "Missing:$missing" >&2
    echo >&2
    echo "Install them with:" >&2
    deps_hint | sed 's/^/  /' >&2
    exit 1
fi

# ---------------- install ----------------
# Stop a daemon still running the copy we are about to overwrite. A daemon is
# a bash process that sourced lib.sh once at startup and keeps those functions
# in memory for life, so installing over it changes nothing it does — the
# upgrade looks like it worked and the new behaviour simply never appears.
# Uninstall already does this; install has to as well.
if [ -r "$LIBDIR/lib.sh" ]; then
    if bash -c ". '$LIBDIR/lib.sh'; daemon_running" 2>/dev/null; then
        bash -c ". '$LIBDIR/lib.sh'; stop_daemon" 2>/dev/null || true
        echo "  stopped the running background app (open BackAtIt to start the new one)"
    fi
fi

echo "Installing to $LIBDIR"
install -d "$LIBDIR" "$BINDIR" "$APPDIR" "$METADIR"
for f in $APP_FILES; do
    install -m 0755 "$SRC/$f" "$LIBDIR/$f"
done
chmod 0644 "$LIBDIR/instruction.txt"
[ -f "$SRC/LICENSE" ] && install -m 0644 "$SRC/LICENSE" "$LIBDIR/LICENSE"

# The icon and the store listing are what make it look like a real app in a
# menu or a software centre rather than a nameless script. A desktop looks for
# the exact pixel size it wants, so every size generated by make-icons.sh is
# installed rather than one big image left to be scaled badly.
ICON_NAME=alarm-clock
for s in $ICON_SIZES; do
    src_icon="$SRC/icons/hicolor/${s}x${s}/apps/backatit.png"
    if [ -f "$src_icon" ]; then
        install -d "$ICONROOT/${s}x${s}/apps"
        install -m 0644 "$src_icon" "$ICONROOT/${s}x${s}/apps/backatit.png"
        ICON_NAME=backatit
    fi
done
if [ -f "$SRC/icons/backatit.svg" ]; then
    install -d "$ICONROOT/scalable/apps"
    install -m 0644 "$SRC/icons/backatit.svg" "$ICONROOT/scalable/apps/backatit.svg"
    ICON_NAME=backatit
fi
[ -f "$SRC/backatit.metainfo.xml" ] &&
    install -m 0644 "$SRC/backatit.metainfo.xml" "$META"

cat > "$LAUNCHER" <<EOF
#!/bin/sh
exec "$LIBDIR/alarm.sh" "\$@"
EOF
chmod 0755 "$LAUNCHER"

cat > "$DESKTOP" <<EOF
[Desktop Entry]
Type=Application
Name=BackAtIt
GenericName=Break timer
Comment=Reminds you to get up and walk while you work
Exec=$LIBDIR/alarm.sh
Icon=$ICON_NAME
Terminal=false
# Ties a running window back to this entry, so the dock shows our icon.
StartupWMClass=backatit
Categories=Utility;
Keywords=break;timer;health;posture;pomodoro;reminder;rsi;stretch;eyes;
StartupNotify=true
EOF
chmod 0644 "$DESKTOP"

command -v update-desktop-database >/dev/null 2>&1 &&
    update-desktop-database "$APPDIR" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null 2>&1 &&
    gtk-update-icon-cache -qtf "$ICONROOT" 2>/dev/null || true

echo
echo "Installed."
echo "  Launch it from your applications menu, or run: $LAUNCHER"
if [ "$MODE" = user ]; then
    case ":$PATH:" in
        *":$BINDIR:"*) ;;
        *) echo "  (note: $BINDIR is not on your PATH)" ;;
    esac
fi
echo "  Settings:   ~/.config/backatit/config"
echo "  Statistics: ~/.local/state/backatit/stats.tsv"
